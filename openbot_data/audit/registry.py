class UnknownFindingCodeError(LookupError):
    """Raised when implementation emits an unregistered stable finding code."""


def _fixture_id(code: str, outcome: str) -> str:
    return f"audit:{code.lower()}:{outcome}"


def _spec(
    code: str,
    severity: str,
    layer: str,
    message: str,
    impact: str,
    fixability: str,
    *,
    applies_to: Tuple[str, ...] = ("video", "lerobot"),
    requirements: Tuple[CapabilityRequirement, ...] = (),
    evidence_fields: Tuple[str, ...] = (),
    location_fields: Tuple[str, ...] = (),
    ordering_fields: Tuple[str, ...] = (),
) -> RuleSpec:
    return RuleSpec(
        rule_id=code.lower().replace("_", "."),
        code=code,
        layer=layer,  # type: ignore[arg-type]
        default_severity=severity,  # type: ignore[arg-type]
        message=message,
        applies_to=applies_to,
        requirements=requirements,
        evidence_fields=evidence_fields,
        location_fields=location_fields,
        impact=impact,
        fixability=fixability,  # type: ignore[arg-type]
        remediation_ref=f"openbot://remediation/{code}",
        ordering_fields=ordering_fields or location_fields,
        positive_fixture=_fixture_id(code, "positive"),
        negative_fixture=_fixture_id(code, "negative"),
    )


