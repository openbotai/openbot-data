def _layered_validation_specs() -> Tuple[RuleSpec, ...]:
    return tuple(
        _spec(
            code,
            severity,
            layer,
            message,
            impact,
            "manual" if severity == "warning" else "delegated",
            applies_to=("lerobot",),
        )
        for code, severity, layer, message, impact in _LAYERED_VALIDATION_FINDINGS
    )


