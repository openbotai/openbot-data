def _build_registry(specs: Tuple[RuleSpec, ...]) -> Mapping[str, RuleSpec]:
    registry = {}
    for spec in specs:
        if spec.code in registry:
            raise RuntimeError(f"duplicate finding registry code: {spec.code}")
        registry[spec.code] = spec
    return MappingProxyType(registry)


FINDING_REGISTRY: Mapping[str, RuleSpec] = _build_registry(_SPECS)


def get_rule_spec(
    code: str,
    *,
    unknown_policy: str = "error",
) -> RuleSpec:
    """Return registered metadata or an explicit conservative fallback."""
    try:
        return FINDING_REGISTRY[code]
    except KeyError as exc:
        if unknown_policy == "error":
            raise UnknownFindingCodeError(
                f"Finding code {code!r} is not present in the static registry"
            ) from exc
        if unknown_policy != "fallback":
            raise ValueError("unknown_policy must be 'error' or 'fallback'") from exc
        # Unknown implementation output must never become less blocking merely
        # because it supplied its own unregistered severity.
        severity = "error"
        return _spec(
            code=code,
            severity=severity,
            layer="provenance",
            message="An unregistered finding was emitted by the audit implementation.",
            impact="validation_contract_is_unknown",
            fixability="not_repairable",
            applies_to=("*",),
        )
